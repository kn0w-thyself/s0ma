# Helper: Locates the artifacts a successful transpile emitted for the given sources — the build manifest, when present, is the authoritative record, with a stem-based scan of candidate directories covering manifest-less cases.
# s0ma: s0ma_src/tools.s0ma:1381 (helper _collect_artifacts)
def _collect_artifacts(
    root: Path,
    sources: list[Path],
    out_dir: Path | None,
) -> list[str]:
    """Locate the artifacts a successful transpile emitted for ``sources``.

The CLI resolves its output directory as: explicit ``--output-dir``,
else the resolved project's ``[tool.s0ma].build_dir`` (flat layout
keyed by *declared module name*), else alongside each source. The
build manifest, when present, is the authoritative record — entries
are matched back to our input sources; a stem-based scan of the
candidate directories covers manifest-less cases."""
    from s0ma_dsl.codegen.build_manifest import BuildManifest
    from s0ma_dsl.project import S0maProject
    wanted = {s.expanduser().resolve() for s in sources}
    candidate_dirs: list[Path] = []
    if out_dir is not None:
        candidate_dirs.append(out_dir)
    else:
        try:
            project = S0maProject.discover(root)
            candidate_dirs.append(Path(project.build_dir))
        except Exception:  # noqa: BLE001 — no [tool.s0ma] table
            pass
    candidate_dirs.extend(source.parent for source in sources)

    found: dict[str, None] = {}  # ordered de-dup
    for directory in candidate_dirs:
        manifest_path = directory / _MANIFEST_NAME
        if manifest_path.is_file():
            try:
                manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                manifest = {}
            for entry in manifest.get("modules", []):
                # SH-M1 (INV-5): project-resolved builds record sources
                # project-root-relative (POSIX) — resolve those against
                # the tool's project root, not the server's CWD. DSL-M3
                # (F-M1-1): the recipe is the one shared dsl helper
                # ``BuildManifest.resolve_source`` (accepts the raw dict
                # entry directly). ``resolve()`` can raise OSError on
                # some platforms, so the comparison stays guarded.
                try:
                    matches = (
                        BuildManifest.resolve_source(entry, root) in wanted
                    )
                except OSError:
                    matches = False
                if not matches:
                    continue
                for field in ("output", "ir", "source_map"):
                    name = entry.get(field)
                    if name and (directory / str(name)).is_file():
                        found[str(directory / str(name))] = None
        for source in sources:
            stem = source.name[: -len(".s0ma")]
            for suffix in _ARTIFACT_SUFFIXES:
                candidate = directory / f"{stem}{suffix}"
                if candidate.is_file():
                    found[str(candidate)] = None
    return list(found)

