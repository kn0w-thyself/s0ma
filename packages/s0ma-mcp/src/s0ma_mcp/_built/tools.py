# Helper: Finds the topics one topic names, by reading the ids out of its own facts and keeping the ones this build actually addresses. Derived rather than authored: a concept names the concepts it relates to, a journey names the surfaces it walks and the concepts it teaches, a document names what it covers — so 'what should I read next' is already written in the record and does not need a second list beside it that somebody has to keep in step. Authority ids are skipped because they ride the answer's own 'Decided by' line, and the id must be in the index before it is offered: a pointer to something this build cannot answer about is worse than no pointer.
# s0ma: s0ma_src/tools.s0ma:1185 (helper _related_topics)
def _related_topics(index: Any, view: Any) -> list[str]:
    """The topics ``view`` names, in the order its facts name them."""
    found: list[str] = []
    for value in view.topical().values():
        parts = value if isinstance(value, tuple) else (value,)
        for part in parts:
            for word in str(part).split():
                candidate = word.strip("`'\",.;:()[]<>")
                if (
                    ":" not in candidate
                    or candidate.startswith("authority:")
                    or candidate == view.id
                    or candidate in found
                    or candidate not in index.views
                ):
                    continue
                found.append(candidate)
    return found[:6]

