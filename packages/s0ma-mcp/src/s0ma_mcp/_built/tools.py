# Helper: Extracts the JSON document from captured CLI stdout via a defensive raw_decode from the first bracket, tolerating stray prose lines; returns None when no JSON document is present.
# s0ma: s0ma_src/tools.s0ma:534 (helper _parse_json_payload)
def _parse_json_payload(stdout: str) -> Any | None:
    """Extract the JSON document from captured CLI stdout.

JSON-mode commands print exactly one document, but a defensive
``raw_decode`` from the first bracket tolerates stray prose lines.
Returns ``None`` when no JSON document is present."""
    starts = [i for i in (stdout.find("{"), stdout.find("[")) if i != -1]
    if not starts:
        return None
    try:
        payload, _ = json.JSONDecoder().raw_decode(stdout[min(starts):])
    except json.JSONDecodeError:
        return None
    return payload

