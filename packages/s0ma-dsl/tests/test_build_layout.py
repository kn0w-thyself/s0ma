def _one_module_project(tmp_path: Path) -> Path:
    """A minimal real project: one source root, one module in it."""
    root = tmp_path / "bare"
    (root / "src").mkdir(parents=True)
    (root / "pyproject.toml").write_text(
        '[project]\nname = "bare"\nversion = "0.1.0"\n\n'
        '[tool.s0ma]\nsource_roots = ["src"]\nmode = "dev"\n',
        encoding="utf-8",
    )
    (root / "src" / "models.s0ma").write_text(
        (Path(__file__).parent / "fixtures" / "multi_module_project" / "models.s0ma")
        .read_text(encoding="utf-8"),
        encoding="utf-8",
        newline="\n",
    )
    return root


class TestTheBareBuildBuildsTheProjectItIsIn:
    """Pilot G2-16 / G1's H-6, and friction F-E2-2 with it.

    Every other command in the retrofit loop defaults to the project;
    ``s0ma build`` exited 2 with an argparse usage error, which cost one
    wasted command per user per conversion and meant no refusal could
    print ``s0ma build`` as a sentence somebody could run.
    """

    def test_it_builds_the_declared_source_roots(self, tmp_path: Path) -> None:
        root = _one_module_project(tmp_path)

        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        assert (root / "bare_build" / "models.py").is_file()

    def test_naming_a_directory_still_means_what_it_meant(
        self, tmp_path: Path
    ) -> None:
        root = _one_module_project(tmp_path)

        assert (
            S0maCLI().run(
                ["--project-root", str(root), "build", str(root / "src")]
            )
            == EXIT_SUCCESS
        )
        assert (root / "bare_build" / "models.py").is_file()

    def test_outside_a_project_it_says_so_rather_than_printing_usage(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        plain = tmp_path / "plain"
        plain.mkdir()

        assert S0maCLI().run(["--project-root", str(plain), "build"]) == 2
        err = capsys.readouterr().err

        assert "there is no s0ma project here" in err
        assert "the following arguments are required" not in err

    def test_a_cache_hit_reports_the_file_you_can_import(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """G1's H-9: the cache's own copy is not this build's output.

        The second build of an unchanged source listed
        ``<build>/.s0ma.cache/models.py`` where the first listed
        ``<build>/models.py`` — read, at the moment somebody had just
        pointed a package at the build directory, as though the alias
        were resolving to a stale file.
        """
        root = _one_module_project(tmp_path)
        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        first = capsys.readouterr().out

        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        second = capsys.readouterr().out

        assert ".s0ma.cache" not in second
        for suffix in (".py", ".s0ma.json", ".s0ma.map"):
            assert f"models{suffix}" in first
            assert f"models{suffix}" in second
        assert "1 module unchanged — kept from the last build" in second

    def test_a_published_file_deleted_by_hand_is_written_again(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """A hit that cannot name a real file is not a hit.

        Nor is it counted as one: the summary used to call the module
        "kept from the last build, not rewritten" while writing it again.
        """
        root = _one_module_project(tmp_path)
        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        capsys.readouterr()
        (root / "bare_build" / "models.py").unlink()

        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        out = capsys.readouterr().out

        assert (root / "bare_build" / "models.py").is_file()
        assert "kept from the last build" not in out

    def test_a_published_ir_deleted_by_hand_is_written_again(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """Every published artifact counts, not only the ``.py``.

        A hit used to look at the ``.py`` alone, and the build then
        crashed reading the ``.s0ma.json`` it had just named as output.
        """
        root = _one_module_project(tmp_path)
        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        capsys.readouterr()
        (root / "bare_build" / "models.s0ma.json").unlink()

        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        out = capsys.readouterr().out

        assert (root / "bare_build" / "models.s0ma.json").is_file()
        assert "kept from the last build" not in out

    def test_an_older_published_file_is_replaced_from_the_source(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """A valid generated file is not enough; it must be this one.

        An earlier build's ``.py`` put back over the current one carries a
        consistent output hash, so nothing reads it as a hand edit — and
        an unchanged source used to be a hit that kept it, stale.
        """
        root = _one_module_project(tmp_path)
        source = root / "src" / "models.s0ma"
        published = root / "bare_build" / "models.py"
        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        older = published.read_bytes()
        source.write_text(
            source.read_text(encoding="utf-8") + "\n", encoding="utf-8", newline="\n"
        )
        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        current = published.read_bytes()
        assert current != older
        published.write_bytes(older)
        capsys.readouterr()

        assert S0maCLI().run(["--project-root", str(root), "build"]) == EXIT_SUCCESS
        out = capsys.readouterr().out

        assert published.read_bytes() == current
        assert "kept from the last build" not in out
