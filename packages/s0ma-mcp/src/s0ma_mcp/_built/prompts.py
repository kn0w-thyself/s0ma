# s0ma: s0ma_src/prompts.s0ma:99 (nerve journey_ladder)
def journey_ladder(journey_id: str) -> str:
    """One recorded journey, as the ladder a prompt walks.

The whole of the F7 prompt binding: the steps a journey prompt
teaches are read from the journey record, so the prompt cannot
say a path the model does not hold, and a step edited in the
model reaches the prompt without anybody editing the prompt."""
    from s0ma_mcp import resources
    lines: list[str] = []
    for position, step in enumerate(
        resources.docs_journey_steps(journey_id), start=1
    ):
        lines.append(
            f"{position}. {_step_call(step['surface'])} — {step['purpose']}"
        )
        lines.append(f"   A good result: {step['expected_outcome']}")
        if step["approval_boundary"]:
            lines.append(f"   Ask first: {step['approval_boundary']}")
    recovery = resources.docs_journey_recovery(journey_id)
    if recovery:
        lines.append("")
        lines.append("When one of these comes back instead:")
        for path in recovery:
            lines.append(
                f"- {path['when']}: {path['action']} "
                f"({_step_call(path['next_surface'])})"
            )
    return "\n".join(lines)

