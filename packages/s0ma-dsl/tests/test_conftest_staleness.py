def test_classify_unrecognized_for_unreadable_file(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A file the OS won't let us read is treated as ``unrecognized``.

    Pins the defensive branch in the classifier: rather than letting
    an unrelated OSError bubble up to the user, we treat unreadable
    files identically to the no-banner case (``unrecognized`` →
    ``customized_stale`` downstream → loud error). This is fail-safe
    over fail-noisy.
    """
    p = tmp_path / "conftest.py"
    p.write_text("# placeholder\n", encoding="utf-8")

    def _boom(*_a, **_kw):
        raise OSError("simulated read failure")

    monkeypatch.setattr(Path, "read_text", _boom)
    assert _classify_conftest(p) == "unrecognized"


