# Helper: Answers whether a JSON object has the field types an s0ma-feedback@1 report has, so submit_feedback can rebuild it as a typed report without the rebuild itself raising on hostile input; deliberately types no parameter as the engine's envelope, because a signature executes at import time and one such annotation would pull the whole feedback engine to module top.
# s0ma: s0ma_src/tools.s0ma:2711 (helper _feedback_shaped)
def _feedback_shaped(payload: dict[str, Any]) -> bool:
    """Whether *payload* carries the field types the schema declares."""
    if any(
        not isinstance(payload.get(key), str)
        for key in ("schema", "category", "impact", "summary")
    ):
        return False
    for key in ("expected", "actual", "details"):
        value = payload.get(key)
        if value is not None and not isinstance(value, str):
            return False
    steps = payload.get("reproduction")
    if steps is not None and (
        not isinstance(steps, list)
        or any(not isinstance(step, str) for step in steps)
    ):
        return False
    context = payload.get("context")
    if context is not None and not isinstance(context, dict):
        return False
    block = payload.get("privacy")
    if block is None:
        return True
    counts = block.get("redacted") if isinstance(block, dict) else None
    return isinstance(counts, dict) and all(
        isinstance(key, str) and isinstance(value, int)
        for key, value in counts.items()
    )

