def host_is_answered(host: str | None) -> bool:
    """Whether a request's Host header names studi0 by one of its names.

``studi0.localhost:5710``, ``LOCALHOST`` and ``127.0.0.1:61234``
are all answered; ``example.test`` is not, under any port. A
bracketed address (``[::1]:5710``) is read up to its closing
bracket, so its colons are not taken for a port."""
    if host is None:
        return True
    written = host.strip()
