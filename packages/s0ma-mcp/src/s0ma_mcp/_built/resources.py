# s0ma: s0ma_src/resources.s0ma:1147 (nerve docs_page_for)
def docs_page_for(topic_id: str) -> str:
    """Where one topic is written down in full, in the s0ma repository.

Six rules, tried in order, and every one of them derived:

1. a command, a setting or a diagnostic code has an anchored
   entry on a generated reference page — the F3 deep link;
2. a concept has a page of its own under the learning
   collection;
3. anything a committed document declares it *covers* is
   written about on that document's own page (this is how a
   journey reaches its guide);
4. a document is written where it says it is written;
5. an authority clause is written in the document it was
   decided in;
6. a served capability with no page of its own is listed in the
   index of everything s0ma can do, and everything else in the
   map of record.

The path is relative to the repository, not to this machine:
these pages ship in the source tree, not in the wheel."""
    from s0ma_dsl.docs_model.learn_pages import page_path
    from s0ma_dsl.docs_model.reference_pages import PAGE_BY_ID_CLASS
    from s0ma_dsl.docs_model.reference_pages import deep_link
    kind = topic_id.partition(":")[0]
    if kind in PAGE_BY_ID_CLASS:
        return deep_link(topic_id, docs_root=DOCS_ROOT)
    if kind == "concept":
        return f"{DOCS_ROOT}/{page_path(topic_id)}"
    bundle = docs_bundle()
    covering = sorted(
        str(document.canonical_source)
        for document in bundle.documents
        if topic_id in document.covers
    )
    if covering:
        return covering[0]
    for document in bundle.documents:
        if document.id == topic_id:
            return str(document.canonical_source)
    for authority in bundle.authorities:
        if authority.id == topic_id:
            return str(authority.source)
    for surface in bundle.surfaces:
        if surface.id == topic_id:
            return DOCS_SURFACES_PAGE
    return DOCS_MAP_PAGE

