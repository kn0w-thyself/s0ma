"""Manifest stub emitter — M-8 (POST-14, 0.15.x).

A successful ``s0ma build`` writes ``<build_dir>/build.s0ma.pyi``
alongside ``__init__.py`` and ``build.s0ma.json``. The stub declares
the typed shape of :func:`s0ma.bootstrap.bootstrap_imports`'s return
value so consumer call sites benefit from mypy / pyright checking
without falling back to ``getattr`` + duck-typing on a
``dict[str, ModuleType]``.

Why a sibling ``.pyi``
----------------------

``bootstrap_imports`` returns ``dict[str, ModuleType]`` — the keys are
the canonical module identities (per §4.10 / ADR-006) and the values
are the imported modules themselves. Without per-build knowledge of
*which* keys are present, consumers cannot have their type-checker
verify ``modules["http_gateway"].run(...)`` resolves to a real symbol.
The companion stub lifts that gap: it declares each module name as a
module-typed attribute and lists every module name in a
``BootstrapModules`` ``TypedDict``. Consumers that pin the build
directory at type-check time (``MYPYPATH=<build_dir>``) get an exact
typed view of the bootstrap dict.

The runtime behaviour of ``bootstrap_imports`` is unchanged — its
return type stays ``dict[str, ModuleType]`` in code, so legacy callers
keep working byte-for-byte. The new value is purely the type-checker
surface; callers may opt in by referencing the stub from their own
type hints, or stay on the legacy duck-typed flow without any change.

Public surface
--------------

- :data:`STUB_FILENAME` — ``build.s0ma.pyi`` (sibling of the manifest).
- :func:`render_manifest_stub` — pure renderer (build → text).
- :func:`emit_manifest_stub` — write the stub to a build directory.

The renderer is deterministic by construction: module names are sorted
alphabetically, the header lists the s0ma-dsl version that produced
the file (but no timestamp — repeat builds within the same project
produce byte-identical output as long as the inputs are unchanged),
and the body is plain ASCII Python.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

    from s0ma_dsl.codegen.build_manifest import BuildManifest


STUB_FILENAME = "build.s0ma.pyi"
"""On-disk filename for the companion type stub. Lives in the build
directory next to ``build.s0ma.json`` and ``__init__.py``."""


def render_manifest_stub(
    manifest: BuildManifest, *, transpiler_version: str
) -> str:
    """Render the ``build.s0ma.pyi`` body for *manifest*.

    The renderer is a pure function of the manifest plus the transpiler
    version string — no clocks, no environment, no filesystem reads —
    so two builds of the same project with the same s0ma-dsl version
    produce byte-identical stubs. Module names are sorted
    alphabetically so the per-module declarations are deterministic
    independent of the order the manifest stores them in (the
    manifest's own ``modules`` list is already alphabetical, but the
    renderer makes the guarantee explicit).

    Stub structure (in this order):

    1. A header comment block naming ``s0ma build`` as the producer
       and pinning the s0ma-dsl version that wrote the file. Consumers
       reading the stub know exactly which transpiler version's
       expectations the file encodes.
    2. The ``from types import ModuleType`` import and a
       ``TypedDict``/``typing`` import block needed by the body.
    3. One ``<module_name>: ModuleType`` declaration per module,
       alphabetically sorted. These let
       ``MYPYPATH=<build_dir>`` resolve ``modules["foo"]`` to the
       declared module shape.
    4. A ``BootstrapModules`` ``TypedDict`` enumerating every module
       name with ``ModuleType`` values, so callers that want the
       full-dict view can declare ``BootstrapModules`` as the return
       type of their bootstrap wrapper.
    5. A module-level ``modules: BootstrapModules`` declaration that
       names the shape directly — useful for callers reading the stub
       file as a reference even without a wrapper.

    An *empty* project (no modules) still produces a valid stub: the
    header, the imports, and an empty ``BootstrapModules`` TypedDict
    body so consumer code that references the name still resolves.
    """
    module_names = sorted(entry.name for entry in manifest.modules)

    lines: list[str] = []

    # Header — fixed prelude + transpiler version. The version is the
    # only build-specific fact that changes the stub bytes across
    # otherwise-identical builds; everything else is derived from
    # manifest contents.
    lines.append("# Auto-generated by `s0ma build` — do not edit.")
    lines.append("#")
    lines.append(
        "# This stub declares the typed identity of every module the "
        "build emitted,"
    )
    lines.append(
        "# so consumers of `s0ma.bootstrap.bootstrap_imports` can have "
        "their type"
    )
    lines.append(
        "# checker (mypy / pyright) verify `modules[\"<name>\"]` resolves "
        "to the real"
    )
    lines.append(
        "# module shape. Point your type-checker at this directory "
        "(MYPYPATH or"
    )
    lines.append(
        "# equivalent) and use `BootstrapModules` as the return type of "
        "your"
    )
    lines.append("# bootstrap wrapper.")
    lines.append("#")
    lines.append(f"# Produced by s0ma-dsl {transpiler_version}.")
    lines.append("")
    lines.append("from types import ModuleType")
    lines.append("from typing import TypedDict")
    lines.append("")

    # Per-module declarations. Each one lets a consumer importing the
    # stub-aware shape resolve the bare module name to the canonical
    # module type, matching what `importlib.import_module(name)`
    # returns at runtime.
    if module_names:
        for name in module_names:
            lines.append(f"{name}: ModuleType")
        lines.append("")

    # BootstrapModules TypedDict — the typed shape of the dict that
    # `bootstrap_imports` returns when filtered to this build's
    # modules. An empty body (no modules) still produces a valid
    # TypedDict declaration so consumers' type-checked code keeps
    # resolving the name.
    lines.append("class BootstrapModules(TypedDict):")
    if module_names:
        for name in module_names:
            lines.append(f"    {name}: ModuleType")
    else:
        lines.append("    pass")
    lines.append("")

    # Bare module declaration so callers grepping the stub for "what's
    # the import-time shape" see one canonical line. Optional from a
    # type-checker standpoint (TypedDict already carries the keys) but
    # cheap to emit and useful for human readers.
    lines.append("modules: BootstrapModules")
    lines.append("")

    return "\n".join(lines)


def emit_manifest_stub(
    manifest: BuildManifest,
    build_dir: Path,
    *,
    transpiler_version: str,
) -> Path:
    """Write the rendered stub to ``build_dir/build.s0ma.pyi``.

    Returns the path the stub was written to. The build pipeline calls
    this immediately after :func:`emit_manifest` so the two files are
    written as a pair on the same build invocation. Like the manifest
    itself, the stub is overwritten on every successful build; there
    is no incremental-merge step — the manifest already carries the
    canonical "what's in this build" answer, so the stub is a pure
    re-derivation of that answer.

    The file is gated on ``errors_so_far == 0`` at the call site (the
    same gate that controls manifest emission). Builds that fail to
    produce a manifest do not produce a stub either; the pair is
    always consistent.
    """
    build_dir.mkdir(parents=True, exist_ok=True)
    stub_path = build_dir / STUB_FILENAME
    body = render_manifest_stub(manifest, transpiler_version=transpiler_version)
    stub_path.write_text(body, encoding="utf-8", newline="\n")
    return stub_path


__all__ = [
    "STUB_FILENAME",
    "emit_manifest_stub",
    "render_manifest_stub",
]
