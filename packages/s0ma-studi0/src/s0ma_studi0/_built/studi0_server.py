def route_request(path: str, session: Studi0Session) -> dict[str, Any]:
    """Answer one requested path with a status, content type, and body.

The whole routing table of this build lives here: the root and
the two ``/assets`` paths serve the sh0w page's own embedded
files, ``/api/state`` and ``/api/graph`` answer from the
session's current reading, and everything else — any other
``/assets/*`` or ``/api/*`` included — reports NOT_FOUND.
Bodies are already encoded, so the request handler only has to
write them.

The assets are served exactly as the build embedded them. There
is no template step and no per-request substitution: the page
learns everything it shows from the graph API, so the bytes on
the wire are the bytes in the model.

The two API routes take ONE snapshot and answer from it, so a
build landing mid-request cannot make ``/api/graph`` return a
graph stamped with a sequence number ``/api/state`` never
reported."""
    if path in ("", "/"):
        return _text_response(_HTML_CONTENT_TYPE, INDEX_HTML)
    if path == "/assets/app.css":
        return _text_response(_CSS_CONTENT_TYPE, APP_CSS)
    if path == "/assets/app.js":
        return _text_response(_JS_CONTENT_TYPE, APP_JS)
    if path == "/api/state":
        return _json_response(200, state_document(read_snapshot(session)))
    if path == "/api/graph":
        document = graph_document(read_snapshot(session))
        if document is None:
            return _json_response(500, NOT_BUILT_ERROR)
        return _json_response(200, document)
    return _json_response(404, NOT_FOUND_ERROR)

