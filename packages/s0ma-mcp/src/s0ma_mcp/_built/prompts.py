# s0ma: s0ma_src/prompts.s0ma:65 (helper _step_call)
def _step_call(surface: str) -> str:
    """How to take the step ``surface`` names, said as an instruction."""
    channel, _, name = surface.partition("/")
    if channel == "mcp:tool":
        return f"Call {name}"
    if channel == "mcp:prompt":
        return f"Use the {name} prompt"
    if channel == "cli:s0ma":
        spelled = name.replace("/", " ")
        return f"Run s0ma {spelled}"
    return f"Use {surface}"

