# Helper: Answers whether one process id is running right now, using only the standard library and without disturbing the process it asks about. This is what makes a leftover studi0 presence file readable as leftover: an unclean shutdown leaves the marker behind, and a dead pid is the evidence that says so.
# s0ma: s0ma_src/tools.s0ma:146 (helper _process_alive)
def _process_alive(pid: int) -> bool:
    """True when ``pid`` names a process that exists right now.

POSIX: signal 0 is the documented existence probe — it runs the
kernel's permission and existence checks and delivers nothing.
``PermissionError`` means the process exists and belongs to
someone else (alive); ``ProcessLookupError`` — and every other
``OSError`` — is read as absent, which is the answer that
suppresses narration, so an unanswerable probe never invents a
watcher.

Windows: ``os.kill`` must NOT be used here. CPython routes every
signal other than CTRL_C_EVENT/CTRL_BREAK_EVENT to
``TerminateProcess``, so ``os.kill(pid, 0)`` would kill the very
studi0 it was asked about. The Win32 probe is the correct
equivalent: open the process for limited query
(PROCESS_QUERY_LIMITED_INFORMATION, 0x1000) and read its exit
code, where STILL_ACTIVE (259) means running. A failed open with
ERROR_ACCESS_DENIED (5) means the pid exists but may not be
looked at, which is alive; any other failure is absent. A
process that really exited with code 259 reads as alive — the
documented, unavoidable ambiguity of that API, and the harmless
direction to be wrong in here."""
    if pid <= 0:
        return False
    if sys.platform == "win32":
        kernel32 = ctypes.windll.kernel32
        handle = kernel32.OpenProcess(0x1000, False, pid)
        if not handle:
            return int(ctypes.GetLastError()) == 5
        try:
            code = ctypes.c_ulong(0)
            if int(kernel32.GetExitCodeProcess(handle, ctypes.byref(code))) == 0:
                return True
            return code.value == 259
        finally:
            kernel32.CloseHandle(handle)
    try:
        os.kill(pid, 0)
    except PermissionError:
        return True
    except OSError:
        return False
    return True

