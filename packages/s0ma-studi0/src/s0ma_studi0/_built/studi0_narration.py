def _reset_log(log: NarrationLog) -> None:
    """Forget everything read so far; the file is a different file."""
    log.offset = 0
    log.entries.clear()
    log.total = 0
    log.invalid = 0

# Helper: Turns the complete lines of one tail into accepted narrations and refusals, in file order, keeping only the most recent window of them. Each line is decoded on its own, so undecodable bytes cost exactly the line they are in.
# s0ma: s0ma_src/studi0_narration.s0ma:285 (helper _consume)
def _consume(log: NarrationLog, complete: bytes) -> bool:
    """Fold ``complete`` into ``log``; True when anything changed."""
    changed = False
    for raw in complete.split(b"\n"):
        if not raw.strip():
            continue
        try:
            record = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, ValueError):
            log.invalid += 1
            changed = True
            continue
        narration = _projected_narration(record, log.total + 1)
        if narration is None:
            log.invalid += 1
            changed = True
            continue
        log.total += 1
        log.entries.append(narration)
        if len(log.entries) > NARRATION_WINDOW:
            del log.entries[: len(log.entries) - NARRATION_WINDOW]
        changed = True
    return changed

