@component(
    name="docs_journeys_resource",
    kind=ComponentKind.FUNCTION,
    layer=Layer.PRESENTATION,
    intent="Serves every worked path this build records, step by step: what the path is for, each step's surface, why it is taken, what a good result looks like, any approval it needs, and what to do when a named thing goes wrong",
    contracts=Contract(
        preconditions=["the packaged snapshot is present and readable"],
        postconditions=["Returns one section per recorded journey with its steps in walking order, read from the same records the journey-shaped prompts render"],
    ),
    dependencies=["docs_bundle", "docs_journey_steps", "docs_snapshot_identity"],
    metadata={"visibility": "PUBLIC", "evaluates_at": "FUNCTION_BOUNDARY", "mcp_uri": "s0ma://docs/journeys", "mcp_mime_type": "text/markdown"},
)
# s0ma: s0ma_src/resources.s0ma:1476 (nerve docs_journeys_resource)
def docs_journeys_resource() -> str:
    """Every worked path through s0ma, step by step.

A journey is a path from a starting point to a finished
outcome: the steps in order, what each is for, and what a good
result looks like. These are the same records the journey
prompts render, so a path read here and a path walked with a
prompt are one path."""
    identity = docs_snapshot_identity()
    journeys = sorted(docs_bundle().journeys, key=lambda record: record.id)
    lines = [
        "# Worked paths through s0ma",
        "",
        f"{len(journeys)} paths, from s0ma {identity['version_line']} "
        f"(snapshot {identity['snapshot_hash']}).",
        "",
    ]
    for journey in journeys:
        lines.extend([
            f"## `{journey.id}`",
            "",
            str(journey.intent),
            "",
            f"Written up in {docs_page_for(journey.id)}.",
            "",
        ])
        for position, step in enumerate(docs_journey_steps(journey.id), start=1):
            lines.append(f"{position}. `{step['surface']}` — {step['purpose']}")
            lines.append(f"   You should see: {step['expected_outcome']}")
            if step["approval_boundary"]:
                lines.append(f"   Needs approval: {step['approval_boundary']}")
        lines.append("")
        for path in journey.recovery_paths:
            lines.append(
                f"- If {path.when}: {path.action} (`{path.next_surface}`)"
            )
        if journey.recovery_paths:
            lines.append("")
    return "\n".join(lines)

