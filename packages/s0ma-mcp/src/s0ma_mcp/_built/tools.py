# Helper: Reorders captured CLI text so the actual cause leads and any advisory 'warning:' lines trail: the DSL CLI can open stderr with an advisory line (e.g. 'Operating without project discovery') that, surfaced verbatim, buries the real error. Generalizes the lead-with-cause split scaffold_module does inline so every tool that surfaces raw CLI output stays cause-first.
# s0ma: s0ma_src/tools.s0ma:604 (helper _lead_with_cause)
def _lead_with_cause(text: str) -> str:
    """Reorder captured CLI output so the cause leads, warnings trail.

Non-empty lines are partitioned into advisory ``warning:`` lines
and everything else; the non-advisory cause lines are emitted
first, the warnings after. Empty or all-warning input is returned
stripped and unreordered."""
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    warnings = [line for line in lines if line.lower().startswith("warning")]
    causes = [line for line in lines if not line.lower().startswith("warning")]
    return "\n".join(causes + warnings)

# Helper: Shapes the shared {ok, exit_code, diagnostics, ...} result for a --format json diagnostics command, summarizing error/warning counts on failure and citing the error-catalog resource for the exact codes returned, so a failing result points the agent at the catalog entries that explain it.
# s0ma: s0ma_src/tools.s0ma:620 (helper _diagnostics_result)
def _diagnostics_result(
    code: int,
    stdout: str,
    stderr: str,
    **extra: Any,
) -> dict[str, Any]:
    """Shape a result for a ``--format json`` diagnostics command."""
    diagnostics = _parse_json_payload(stdout)
    result: dict[str, Any] = {
        "ok": code == 0,
        "exit_code": code,
        "diagnostics": diagnostics,
        **extra,
    }
    if diagnostics is None and stdout.strip():
        result["output"] = stdout.strip()
    if code != 0:
        summary = (
            diagnostics.get("summary") if isinstance(diagnostics, dict) else None
        )
        if summary:
            result["error"] = (
                f"{summary.get('errors', '?')} error(s), "
                f"{summary.get('warnings', '?')} warning(s) "
                f"in {summary.get('files_processed', '?')} file(s)"
            )
        else:
            # P2: lead with the actual cause, not an advisory line.
            result["error"] = (
                _lead_with_cause(stderr or stdout) or f"exit code {code}"
            )
        codes = _diagnostic_codes(diagnostics)
        if codes:
            # D1: a per-code deep anchor into the error catalog, so a
            # failing diagnostic points at its own entry — the exact
            # code is findable at that anchor in the served
            # s0ma://guide/errors text (a flat code table).
            anchors = ", ".join(
                f"s0ma://guide/errors#{code_name}" for code_name in codes
            )
            result["error_help"] = (
                "Apply each diagnostic's remediation, then look each "
                f"code up at its own anchor in the error catalog: "
                f"{anchors}. Compact authoring rules: "
                "s0ma://guide/survival-card."
            )
    return result

# Helper: Adds the narrowest resolvable module/component owner and authored intent to check findings by matching each source line against the parsed declaration spans, leaving unparsable findings unchanged.
# s0ma: s0ma_src/tools.s0ma:671 (helper _attach_finding_owners)
def _attach_finding_owners(
    diagnostics: Any,
    root: Path,
) -> None:
    """Annotate parseable check findings with owner and intent in place."""
    from s0ma_dsl.parser import parse_s0ma
    if not isinstance(diagnostics, dict):
        return
    parsed_by_path: dict[Path, Any] = {}
    for bucket in ("errors", "warnings"):
        for finding in diagnostics.get(bucket, []):
            if not isinstance(finding, dict):
                continue
            raw_file = finding.get("file")
            raw_line = finding.get("line")
            if not isinstance(raw_file, str) or not isinstance(raw_line, int):
                continue
            candidate = Path(raw_file)
            if not candidate.is_absolute():
                candidate = root / candidate
            candidate = candidate.resolve()
            if not candidate.is_file() or not candidate.is_relative_to(root):
                continue
            if candidate not in parsed_by_path:
                try:
                    parsed_by_path[candidate] = parse_s0ma(
                        candidate.read_text(encoding="utf-8"),
                        filename=str(candidate),
                    )
                except Exception:  # noqa: BLE001 — check owns parse errors
                    parsed_by_path[candidate] = None
            parsed = parsed_by_path[candidate]
            if parsed is None:
                continue
            declarations = [parsed.module, *parsed.all_declarations]
            owners = [
                declaration
                for declaration in declarations
                if declaration.location is not None
                and declaration.location.start_line <= raw_line
                <= declaration.location.end_line
            ]
            if not owners:
                continue
            owner = min(
                owners,
                key=lambda declaration: (
                    declaration.location.end_line
                    - declaration.location.start_line
                ),
            )
            finding["owner"] = f"{parsed.module.name}::{owner.name}"
            finding["owner_intent"] = str(owner.intent)

