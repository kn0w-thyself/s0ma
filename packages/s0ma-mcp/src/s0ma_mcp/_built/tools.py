# Helper: Builds the project_status `runtime` section: the declared run/health commands, the env contract summary (declared / required / missing-required, read from the LIVE process environment by NAME only — never leaking a value), the runtime state_paths that must never be reverted, and whether any runbook is declared; an undeclared runbook yields a teaching hint pointing at s0ma://project/runbook that LEADS with the not-a-fault disclaimer so a mid-diagnosis agent cannot read runbook_declared: false as a service defect.
# s0ma: s0ma_src/tools.s0ma:2161 (helper _runtime_section)
def _runtime_section(project: Any) -> dict[str, Any]:
    """Shape the ``runtime`` section of a ``project_status`` result (O1).

Reads the resolved project's ops-runbook fields plus the LIVE
process environment — presence only, by variable name. A declared
default or a live value is NEVER read into the result (names only:
the no-secret-leak posture). ``missing_required`` lists the
required variables absent from ``os.environ``. When no runbook key
is declared the section still returns, carrying a ``hint`` naming
what to declare and pointing at the ``s0ma://project/runbook``
resource."""
    env_declared: list[dict[str, Any]] = []
    missing_required: list[str] = []
    for var_name in sorted(project.env):
        spec = project.env[var_name]
        env_declared.append({
            "name": var_name,
            "required": bool(spec.required),
            "fail_fast": bool(spec.fail_fast),
            "has_default": spec.default is not None,
        })
        if spec.required and var_name not in os.environ:
            missing_required.append(var_name)

    declared = bool(
        project.run_command
        or project.health_command
        or project.env
        or project.state_paths
        or project.runbook_notes
    )
    section: dict[str, Any] = {
        "runbook_declared": declared,
        "run_command": project.run_command,
        "health_command": project.health_command,
        "env": env_declared,
        "missing_required_env": missing_required,
        "state_paths": list(project.state_paths),
        "runbook_notes": list(project.runbook_notes),
        "runbook_resource": "s0ma://project/runbook",
    }
    if not declared:
        section["hint"] = (
            "no ops runbook declared — this is a documentation gap, "
            "never a service fault: an undeclared runbook cannot break "
            "or degrade a running service, so a live failure is never "
            "caused by a missing runbook. Diagnose from observed "
            "behavior, configuration, and environment; then add "
            "run_command / health_command / state_paths / "
            "[tool.s0ma.env.*] under [tool.s0ma] and read "
            "s0ma://project/runbook. state_paths mark runtime state "
            "that must never be reverted, restored from git, or "
            "regenerated."
        )
    return section

# Helper: Classifies an adoption-ledger record as a current handwritten Python module row only when the file still exists inside the project and has not become a transpiler-owned artifact.
