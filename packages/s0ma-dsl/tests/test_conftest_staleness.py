"""G5 — versioned conftest banner + staleness detection (feedback 5–6 cleanup).

Pins the G5 contract end-to-end:

1. ``_generate_conftest`` emits a four-line banner (version + checksum
   + do-not-hand-edit + ``--force`` regeneration pointer) above the
   body it has always emitted; the body is unchanged in shape.
2. ``_compute_conftest_body_checksum`` is stable across runs (same
   input → same hex digest).
3. The banner's checksum line agrees with the body byte-for-byte:
   re-rendering the body with the same kinds/layers and re-computing
   the checksum reproduces the embedded value.
4. ``_parse_conftest_banner`` round-trips a freshly-generated conftest
   and returns ``(None, None)`` for anything else.
5. ``_classify_conftest`` correctly distinguishes the five states:
   ``absent``, ``current``, ``untouched_stale``, ``customized_stale``,
   ``unrecognized``.
6. ``_cmd_test`` refuses to invoke pytest when the conftest is
   ``customized_stale`` or ``unrecognized`` and exits non-zero before
   reaching the build pass.
7. ``_cmd_test`` auto-regenerates non-destructively for the
   ``untouched_stale`` branch (with a runtime-monkeypatched registry,
   since the on-disk ``STALE_GENERATED_CONFTEST_VERSION_CHECKSUMS``
   shape is empty on initial G5 release).
8. ``s0ma test-conftest`` (no flag) refuses to overwrite an existing
   file; ``--force`` regenerates unconditionally.

The fixture under ``tests/fixtures/stale_conftest_project/`` carries
a minimal one-source-root, one-test-root project so the integration
tests have a real ``s0ma test`` invocation to exercise.

See ``plans/5-6_cleanup_plan.md`` G5 for the surrounding context.
"""

