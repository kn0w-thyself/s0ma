    text = load_docs_model()
    assert '"schema": "s0ma-docs-model@1"' in text
    bundle = docs_bundle()
    index = docs_topic_index()
    assert docs_bundle() is bundle  # parsed once, not per question
    assert len(index.ids()) == (
        len(bundle.authorities)
        + len(bundle.concepts)
        + len(bundle.documents)
        + len(bundle.journeys)
        + len(bundle.sequences)
        + len(bundle.surfaces)
    )

    identity = docs_snapshot_identity()
    assert set(identity) == {"release_version", "snapshot_hash"}
    assert identity["snapshot_hash"].startswith("sha256:")

    # Every addressable topic reaches a written-down place, and the
    # path it reaches is relative to the repository — never a machine
    # path, never absolute, never a guess above the checkout.
    for identifier in index.ids():
        page = docs_page_for(identifier)
        assert page, identifier
        assert not page.startswith("/"), identifier
        assert ".." not in page, identifier
    # The four id classes that have a page of their own reach it under
    # the documentation root, which is what the deep-link convention
    # promises a reader following one.
    for identifier in index.ids():
        if identifier.partition(":")[0] in {"cli", "config", "concept", "diagnostic"}:
            assert docs_page_for(identifier).startswith(f"{DOCS_ROOT}/"), identifier

    steps = docs_journey_steps("journey:mcp-authoring-loop")
    assert steps, "the mcp authoring journey records no steps"
    assert [step["surface"] for step in steps] == [
        step.surface
        for journey in bundle.journeys
        if journey.id == "journey:mcp-authoring-loop"
        for step in journey.steps
    ]
    assert docs_journey_steps("journey:nothing-called-this") == []

    recovery = docs_journey_recovery("journey:mcp-authoring-loop")
    assert recovery, "the mcp authoring journey records no recovery paths"
    assert [path["when"] for path in recovery] == [
        path.when
        for journey in bundle.journeys
        if journey.id == "journey:mcp-authoring-loop"
        for path in journey.recovery_paths
    ]
    assert docs_journey_recovery("journey:nothing-called-this") == []

    served_index = docs_index_resource()
    # The LABELLED version, not the bare one: the bare number is a
    # substring of the labelled line, so asserting it would pass on a
    # blurb that had quietly dropped the channel (H2).
    assert identity["version_line"] in served_index
    assert identity["snapshot_hash"] in served_index
    assert "learn_s0ma" in served_index
    assert f"{len(index.ids())} topics this build addresses" in served_index
    # Every category the snapshot holds has a line, and every line has
    # authored words: a category nobody described would still be listed,
    # and this is what says so out loud.
    for prefix in sorted({identifier.partition(":")[0] for identifier in index.ids()}):
        assert f"- {prefix}: " in served_index, prefix
        assert prefix in DOCS_CATEGORY_WORDS, prefix
    assert "s0ma://docs/user-guide" in served_index  # the other server, named
    # The index is the first thing an agent reads about s0ma itself, so
    # it is held to the survival card's context-economy ceiling: it
    # grows by category, never by topic, and this is what says so.
    assert len(served_index.encode("utf-8")) < 4_096

    concepts = docs_concepts_resource()
    for record in bundle.concepts:
        assert f"`{record.id}`" in concepts
        assert record.summary in concepts

    journeys = docs_journeys_resource()
    for journey in bundle.journeys:
        assert f"`{journey.id}`" in journeys
        for step in journey.steps:
            assert step.purpose in journeys

