# Helper: Answers the two shapes a question that reached no single topic takes, and answers them differently because they are different facts: several candidates of equal standing, which the resolver returns rather than picks because picking between equals is a guess; or nothing at all, which comes back with the nearest ids this build does address so the next ask is a real one. Both carry a next action, so a miss is a step rather than a dead end.
# s0ma: s0ma_src/tools.s0ma:1218 (helper _topic_not_resolved)
def _topic_not_resolved(
    index: Any,
    asked: str,
    resolution: Any,
) -> dict[str, Any]:
    """The answer to a question that named no one topic."""
    from s0ma_dsl.docs_model.resolve import nearest
    state = resolution.state()
    if state == "ambiguous":
        candidates = [
            {"topic_id": item.id, "category": item.group, "why": item.reason}
            for item in resolution.candidates
        ]
        return {
            "ok": False,
            "state": state,
            "asked": asked,
            "error": (
                f"{asked!r} could mean {len(candidates)} different topics, "
                f"and choosing between equals would be a guess."
            ),
            "candidates": candidates,
            "remediation": (
                "Ask again with the id of the one you meant — every "
                "candidate above carries it."
            ),
            "next_actions": [{
                "tool": "learn_s0ma",
                "arguments": {"topic": candidates[0]["topic_id"]},
                "reason": (
                    f"{candidates[0]['topic_id']} is the first of the "
                    f"topics {asked!r} could have meant."
                ),
            }],
        }
    finding = resolution.finding
    near = list(nearest(index, asked))
    answer: dict[str, Any] = {
        "ok": False,
        "state": state,
        "asked": asked,
        "code": finding.code if finding is not None else "",
        "error": finding.message if finding is not None else "",
        "remediation": finding.remediation if finding is not None else "",
        "nearest": near,
    }
    if near:
        answer["next_actions"] = [{
            "tool": "learn_s0ma",
            "arguments": {"topic": near[0]},
            "reason": (
                f"{near[0]} is the nearest thing this build "
                f"addresses to {asked!r}."
            ),
        }]
    return answer

