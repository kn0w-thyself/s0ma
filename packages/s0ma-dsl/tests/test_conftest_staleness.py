def _extract_patch_target_strings(body: str) -> list[str]:
    """Return the first-positional string literal from every
    ``unittest.mock.patch(...)`` call in *body*, parsed via ``ast``.

    The walker accepts both bare ``patch("...")`` and attributed
    ``mock.patch("...")`` forms, since the conftest body imports
    ``patch`` directly today but a future refactor might switch to
    ``import unittest.mock``. Calls whose first positional argument is
    not a string literal (e.g. ``patch.object(...)``) are skipped — the
    G10 contract concerns string-target patches only.
    """
    tree = ast.parse(body)
    targets: list[str] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        # Match either ``patch(...)`` or ``<x>.patch(...)``.
        is_patch = (
            (isinstance(func, ast.Name) and func.id == "patch")
            or (
                isinstance(func, ast.Attribute) and func.attr == "patch"
            )
        )
        if not is_patch:
            continue
        if not node.args:
            continue
        first = node.args[0]
        if isinstance(first, ast.Constant) and isinstance(first.value, str):
            targets.append(first.value)
    return targets


def test_conftest_patch_targets_resolve_against_live_modules() -> None:
    """G10 regression — the body's ``patch("...")`` strings name
    attributes that actually exist at test time.

    This is the contract G9-1 broke silently: the template wrote
    ``s0ma.runtime_bridge.registration.register_module``, but
    ``s0ma.runtime_bridge`` is not an attribute of the ``s0ma``
    package on the current framework. ``unittest.mock.patch`` resolves
    targets via dotted attribute lookup, so a non-existent intermediate
    raises ``AttributeError`` at fixture setup time — several stages
    downstream of the cause.

    The check is structural: render the body, walk every patch target
    via ``ast``, split the dotted path into ``module.tail``, import
    the module, and walk ``hasattr`` down the tail. Every target must
    start with a known canonical root (``s0ma`` or ``s0ma_dsl``) so a
    future contributor adding a patch with a typo'd root can't slip
    through. A target that resolves cleanly under both roots is fine;
    a target that fails to resolve at all surfaces here, not at
    consumer-side pytest collection.
    """
    body = _render_conftest_body(
        kinds_used={"FUNCTION"}, layers_used={"DOMAIN"}
    )
    targets = _extract_patch_target_strings(body)

    # The current body patches exactly two attributes — locking the
    # count guards against a future edit that adds a patch site
    # without verifying its target resolves.
    assert len(targets) == 2, (
        f"Expected 2 patch targets in conftest body; got {len(targets)}: "
        f"{targets!r}"
    )

    canonical_roots = ("s0ma.", "s0ma_dsl.")
    for target in targets:
        assert target.startswith(canonical_roots), (
            f"patch target {target!r} does not start with a canonical "
            f"root {canonical_roots!r}; the conftest is meant to mock "
            f"the s0ma framework or the s0ma-dsl runtime bridge only."
        )

        # Walk the dotted path: import the longest importable prefix,
        # then assert hasattr down the remaining tail.
        parts = target.split(".")
        module_name = parts[0]
        last_imported = importlib.import_module(module_name)
        idx = 1
        # Try importing successive submodules until import fails; fall
        # back to attribute traversal for the rest.
        while idx < len(parts):
            candidate = ".".join(parts[: idx + 1])
            try:
                last_imported = importlib.import_module(candidate)
            except ImportError:
                break
            idx += 1
        obj = last_imported
        for attr in parts[idx:]:
            assert hasattr(obj, attr), (
                f"patch target {target!r} unresolvable: "
                f"{type(obj).__name__} {obj!r} has no attribute {attr!r}. "
                f"This is the G9-1 failure mode: a stale patch path that "
                f"only surfaces at consumer pytest fixture-setup time."
            )
            obj = getattr(obj, attr)


