def read_narrations(log: NarrationLog, project_root: Path) -> bool:
    """Tail the session log under ``project_root`` into ``log``.

Byte offsets rather than line counts, because the writer is
appending to the same file studi0 is reading: only the bytes up
to the last newline are a complete record of anything, and the
offset is what makes the next tick pick up exactly where this
one stopped.

A file that has become SHORTER than the offset is not the file
that was being read — a new session, or a cleared log — so the
reading starts over rather than splicing.

Args:
    log: The reading to advance, in place.
    project_root: The project whose log to tail.

Returns:
    True when the reading changed — a narration was accepted, a
    line was refused, or the log was replaced."""
    path = session_log_path(project_root)
    with log.lock:
        try:
            size = path.stat().st_size
        except OSError:
            # No log, no directory, no permission: nothing narrated.
            return False
        reset = False
        if size < log.offset:
            _reset_log(log)
            reset = True
        if size == log.offset:
            return reset
        try:
            with path.open("rb") as handle:
                handle.seek(log.offset)
                chunk = handle.read(size - log.offset)
        except OSError:
            return reset
        cut = chunk.rfind(b"\n")
        if cut < 0:
            # Only a torn trailing line so far — look again next tick.
            return reset
        log.offset += cut + 1
        return _consume(log, chunk[:cut]) or reset

