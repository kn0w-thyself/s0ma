# Helper: Reads the canonical build manifest and IR imports to turn one inspected module's depends-on and depended-by project neighbors into structured inspect_module next actions.
# s0ma: s0ma_src/tools.s0ma:972 (helper _module_neighbor_actions)
def _module_neighbor_actions(
    root: Path,
    module: str,
) -> list[dict[str, Any]]:
    """Return canonical module-neighbor inspection actions."""
    from s0ma_dsl.codegen.build_manifest import load_manifest
    from s0ma_dsl.project import S0maProject
    try:
        project = S0maProject.discover(root)
        manifest = load_manifest(Path(project.build_dir))
    except Exception:  # noqa: BLE001 — inspection fallback stays available
        return []
    module_names = {str(entry.name) for entry in manifest.modules}
    dependencies: dict[str, set[str]] = {name: set() for name in module_names}
    for entry in manifest.modules:
        try:
            document = json.loads(
                (Path(project.build_dir) / entry.ir).read_text(encoding="utf-8")
            )
        except (OSError, json.JSONDecodeError):
            continue
        uses = document.get("imports", {}).get("uses", {})
        raw_values = uses.get("value", []) if uses.get("state") == "value" else []
        if not isinstance(raw_values, list):
            continue
        for raw in raw_values:
            if not isinstance(raw, str):
                continue
            target = raw.replace("::", ".").split(".", 1)[0]
            if target in module_names and target != entry.name:
                dependencies[str(entry.name)].add(target)

    actions: list[dict[str, Any]] = []
    for target in sorted(dependencies.get(module, set())):
        actions.append({
            "tool": "inspect_module",
            "arguments": {"project_root": str(root), "module": target},
            "reason": f"Inspect dependency neighbor {target} before changing {module}.",
            "relationship": "depends_on",
        })
    for target in sorted(
        name for name, deps in dependencies.items() if module in deps
    ):
        actions.append({
            "tool": "inspect_module",
            "arguments": {"project_root": str(root), "module": target},
            "reason": f"Inspect dependent neighbor {target} before changing {module}.",
            "relationship": "depended_by",
        })
    return actions

# Helper: Finds a named roster-adopted Python record and asks the DSL static deriver for its provenance-marked draft, never importing the target and never presenting the result as canonical IR.
