#!/usr/bin/env python3
"""Draw the root README's first picture: the anatomy of one real nerve.

Every word in the picture is read from a project this script makes on the
spot with ``s0ma new project shop --template service`` and the working tree's
own s0ma. The contract lines come from the module's build record and the code
comes from the ``.s0ma`` source that record points at. Nothing is typed in by
hand, so the picture cannot say something the language does not.

Default mode is a read-only check: it draws the picture again and compares it
with the two committed files, one per palette. Pass ``--write`` after the
service scaffold or this script has deliberately changed, review the diff, and
run the default mode again. ``packages/s0ma-dsl/tests/test_readme_hero.py``
runs the same check in the gate.

Output is deterministic: the same scaffold gives the same text.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "docs/media/readme"

#: The scaffold the picture is drawn from, and the part of it that is drawn.
SCAFFOLD_ARGS = ("new", "project", "shop", "--template", "service")
SCAFFOLD_LABEL = "from: s0ma " + " ".join(SCAFFOLD_ARGS)
MODULE = "api_presentation"
COMPONENT = "handle_order_request"

SANS = '-apple-system, BlinkMacSystemFont, "Segoe UI", "Noto Sans", Helvetica, Arial, sans-serif'
MONO = 'ui-monospace, SFMono-Regular, "SF Mono", Menlo, Consolas, "Liberation Mono", monospace'

PALETTES: dict[str, dict[str, str]] = {
    "light": {
        "card": "#ffffff", "card_line": "#d0d7de", "ink": "#1f2328", "muted": "#59636e",
        "accent": "#09c6d2", "accent_ink": "#0a7780", "accent_soft": "#e9fafb",
        "code_bg": "#f6f8fa", "box": "#f6f8fa", "box_line": "#d0d7de",
        "gate": "#fff8e5", "gate_line": "#d4a72c", "gate_ink": "#7d4e00",
    },
    "dark": {
        "card": "#161b22", "card_line": "#30363d", "ink": "#e6edf3", "muted": "#9198a1",
        "accent": "#09c6d2", "accent_ink": "#56d9e2", "accent_soft": "#0b2b2f",
        "code_bg": "#0d1117", "box": "#21262d", "box_line": "#30363d",
        "gate": "#2b2005", "gate_line": "#9e6a03", "gate_ink": "#f2cc60",
    },
}

WIDTH = 880
CARD_X, CARD_W = 16, 848
INNER_X, INNER_W = 36, 808
LABEL_X, VALUE_X = 52, 178
VALUE_CHARS = 82  # conservative for a 650px column of 14.5px sans
LINE = 21
SHOWN = ("intent", "guarantees", "forbids", "depends_on")

READERS = (
    ("You", "read why it exists"),
    ("Your coding agent", "works inside its limits"),
    ("The AI running your app", "asks before it acts"),
)
GATE = ("The build", "refuses missing or drifted")

#: An XML comment may not contain two hyphens in a row, so no flag is spelled here.
BANNER = (
    "<!-- Generated by scripts/render_readme_hero.py from the service scaffold that\n"
    "     s0ma new project makes. Do not edit by hand: run that script in write\n"
    "     mode instead. -->"
)


class HeroError(RuntimeError):
    """The scaffold could not be made, or is not shaped the way the picture needs."""


def scaffold(parent: Path) -> Path:
    """Make the service scaffold under *parent* with this tree's s0ma and return it."""
    done = subprocess.run(
        [sys.executable, "-m", "s0ma_dsl", *SCAFFOLD_ARGS],
        cwd=parent,
        capture_output=True,
        text=True,
        check=False,
    )
    project = parent / "shop"
    if done.returncode != 0 or not (project / "build").is_dir():
        raise HeroError(f"`s0ma {' '.join(SCAFFOLD_ARGS)}` failed:\n{done.stdout}{done.stderr}")
    return project


def load(project: Path) -> dict[str, Any]:
    """Read everything the picture shows out of the built project."""
    record = json.loads((project / "build" / f"{MODULE}.s0ma.json").read_text(encoding="utf-8"))
    comp = next(c for c in record["components"] if c["canonical_id"].endswith(f"::{COMPONENT}"))
    source = (project / record["module"]["source_file"]).read_text(encoding="utf-8").splitlines()
    block = source[comp["location"]["start_line"] - 1 : comp["location"]["end_line"]]
    divider = next(i for i, line in enumerate(block) if line.strip() == "---")
    declared = [ln for ln in block[1:divider] if ln.startswith("    ") and not ln.startswith("     ")]
    code = textwrap.dedent("\n".join(block[divider + 1 :])).splitlines()
    while code and not code[-1].strip():
        code.pop()
    for label in ("guarantees", "forbids"):
        if comp["fields"][label].get("state") != "value":
            raise HeroError(f"{COMPONENT} no longer writes `{label}`, which the picture shows")
    return {
        "name": COMPONENT,
        "intent": comp["intent"]["value"],
        "guarantees": comp["fields"]["guarantees"]["value"],
        "forbids": comp["fields"]["forbids"]["value"],
        "edges": [e for e in record["edges"]["authored"] if e["source"] == comp["canonical_id"]],
        "more": len(declared) - len(SHOWN),
        "code": code,
    }


def render(data: dict[str, Any], p: dict[str, str]) -> str:
    """One palette's picture, as SVG text."""
    out: list[str] = []
    y = 16

    def text(
        x: float, yy: float, s: str, *, size: float = 14.5, fill: str | None = None,
        font: str = SANS, weight: int | None = None, anchor: str | None = None,
        style: str | None = None,
    ) -> None:
        attrs = [f'x="{x}"', f'y="{yy}"', f'font-size="{size}"', f'fill="{fill or p["ink"]}"',
                 f"font-family='{font}'"]
        if weight:
            attrs.append(f'font-weight="{weight}"')
        if anchor:
            attrs.append(f'text-anchor="{anchor}"')
        if style:
            attrs.append(f'font-style="{style}"')
        out.append(f'<text {" ".join(attrs)} xml:space="preserve">{escape(s)}</text>')

    card_top = y

    # header: what kind of thing this is, its name, and where it really comes from
    y += 36
    out.append(f'<rect x="{INNER_X}" y="{y - 17}" width="56" height="24" rx="12" fill="{p["accent_soft"]}" stroke="{p["accent"]}" stroke-width="1"/>')
    text(INNER_X + 28, y, "nerve", size=12.5, fill=p["accent_ink"], font=MONO, anchor="middle", weight=600)
    text(INNER_X + 68, y + 1, data["name"], size=16.5, font=MONO, weight=600)
    text(INNER_X + INNER_W, y, SCAFFOLD_LABEL, size=12, fill=p["muted"], font=MONO, anchor="end")
    y += 22

    # the contract: the lines a person wrote about this part
    rows: list[tuple[str, list[tuple[str, str]]]] = []
    for label in ("intent", "guarantees", "forbids"):
        rows.append((label, [(ln, "value") for ln in textwrap.wrap(data[label], VALUE_CHARS)]))
    dep_lines: list[tuple[str, str]] = []
    for edge in data["edges"]:
        target = edge["target"].replace("::", ".")
        dep_lines.append((f'{target}   {edge["relation"].lower()}, carrying {edge["carries"]}', "dep"))
    rows.append(("depends_on", dep_lines or [("none", "value")]))

    block_top = y
    cursor = block_top + 14
    drawn: list[tuple[str, int, list[tuple[str, str]]]] = []
    for label, lines in rows:
        cursor += LINE - 5
        drawn.append((label, cursor, lines))
        cursor += LINE * (len(lines) - 1) + 14
    cursor += LINE - 5
    more_y = cursor
    block_h = more_y + 16 - block_top
    out.append(f'<rect x="{INNER_X}" y="{block_top}" width="{INNER_W}" height="{block_h}" rx="8" fill="{p["accent_soft"]}" stroke="{p["accent"]}" stroke-width="1"/>')
    for label, yy, lines in drawn:
        text(LABEL_X, yy, label, size=13, fill=p["accent_ink"], font=MONO, weight=600)
        for i, (line, kind) in enumerate(lines):
            if kind == "dep":
                name, _, note = line.partition("   ")
                text(VALUE_X, yy + i * LINE, name, size=13.5, font=MONO)
                text(VALUE_X + len(name) * 8.2 + 14, yy + i * LINE, note, size=13.5, fill=p["muted"])
            else:
                text(VALUE_X, yy + i * LINE, line)
    text(VALUE_X, more_y, f"… and {data['more']} more lines, each one answered, most of them with none",
         size=13, fill=p["muted"], style="italic")
    y = block_top + block_h

    # the divider the language uses, then the code exactly as written
    y += 26
    text(LABEL_X, y, "---", size=13, fill=p["muted"], font=MONO, weight=600)
    text(LABEL_X + 40, y, "then ordinary Python", size=13, fill=p["muted"])
    y += 12
    code_h = len(data["code"]) * 20 + 22
    out.append(f'<rect x="{INNER_X}" y="{y}" width="{INNER_W}" height="{code_h}" rx="8" fill="{p["code_bg"]}" stroke="{p["card_line"]}" stroke-width="1"/>')
    for i, line in enumerate(data["code"]):
        text(LABEL_X, y + 26 + i * 20, line, size=13, font=MONO)
    y += code_h + 20
    card = (f'<rect x="{CARD_X}" y="{card_top}" width="{CARD_W}" height="{y - card_top}" rx="12" '
            f'fill="{p["card"]}" stroke="{p["card_line"]}" stroke-width="1"/>')

    # who reads it, and what holds it true
    y += 30
    box_w, gap = 200, 16
    xs = [CARD_X + i * (box_w + gap) for i in range(4)]
    read_l, read_r = xs[0], xs[2] + box_w
    mid = (read_l + read_r) / 2
    out.append(f'<path d="M{read_l} {y + 8} V{y} H{mid - 36} M{mid + 36} {y} H{read_r} V{y + 8}" fill="none" stroke="{p["muted"]}" stroke-width="1"/>')
    text(mid, y + 4, "read by", size=12.5, fill=p["muted"], anchor="middle")
    gate_l, gate_r = xs[3], xs[3] + box_w
    gate_mid = (gate_l + gate_r) / 2
    out.append(f'<path d="M{gate_l} {y + 8} V{y} H{gate_mid - 48} M{gate_mid + 48} {y} H{gate_r} V{y + 8}" fill="none" stroke="{p["gate_line"]}" stroke-width="1"/>')
    text(gate_mid, y + 4, "held true by", size=12.5, fill=p["gate_ink"], anchor="middle")
    y += 18
    for x, (title, sub) in zip(xs, READERS, strict=False):
        out.append(f'<rect x="{x}" y="{y}" width="{box_w}" height="62" rx="8" fill="{p["box"]}" stroke="{p["box_line"]}" stroke-width="1"/>')
        text(x + box_w / 2, y + 26, title, weight=600, anchor="middle")
        text(x + box_w / 2, y + 46, sub, size=12.5, fill=p["muted"], anchor="middle")
    out.append(f'<rect x="{xs[3]}" y="{y}" width="{box_w}" height="62" rx="8" fill="{p["gate"]}" stroke="{p["gate_line"]}" stroke-width="1"/>')
    text(xs[3] + box_w / 2, y + 26, GATE[0], weight=600, fill=p["gate_ink"], anchor="middle")
    text(xs[3] + box_w / 2, y + 46, GATE[1], size=12.5, fill=p["gate_ink"], anchor="middle")
    height = y + 62 + 16

    title = f"The anatomy of one s0ma nerve, {data['name']}"
    desc = ("A declared part of a program. Above a divider it says what it is for, what it guarantees, "
            "what it must never do and what it depends on. Below the divider is ordinary Python. "
            "It is read by you, by your coding agent and by the AI running your app, and the build holds it true.")
    head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height}" viewBox="0 0 {WIDTH} {height}" '
            f'role="img" aria-labelledby="t d"><title id="t">{escape(title)}</title><desc id="d">{escape(desc)}</desc>')
    return "\n".join([BANNER, head, card, *out, "</svg>"]) + "\n"


def rendered() -> dict[str, str]:
    """Both pictures, drawn fresh: file name to SVG text."""
    with tempfile.TemporaryDirectory(prefix="s0ma-readme-hero-") as scratch:
        data = load(scaffold(Path(scratch)))
    return {f"nerve-anatomy-{name}.svg": render(data, palette) for name, palette in PALETTES.items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write the two pictures instead of checking them")
    args = parser.parse_args(argv)
    try:
        pictures = rendered()
    except HeroError as exc:
        print(f"README hero error: {exc}")
        return 2
    stale = []
    for name, svg in pictures.items():
        target = OUT_DIR / name
        if args.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(svg, encoding="utf-8", newline="\n")
        elif not target.is_file() or target.read_text(encoding="utf-8") != svg:
            stale.append(name)
    if stale:
        print(f"README hero: stale ({', '.join(stale)})")
        print("Run `python scripts/render_readme_hero.py --write` and review.")
        return 1
    print(f"README hero: {'updated' if args.write else 'current'} ({len(pictures)} pictures)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
